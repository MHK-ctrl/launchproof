import path from 'node:path';

import type { LaunchProofConfig } from './config/schema.js';
import { createCheck, createFinding } from './checks.js';
import type { DiscoveryResult } from './discovery.js';
import { pathExists } from './fs-utils.js';
import type { CheckResult, Finding } from './types.js';

const GITIGNORE_REQUIRED = ['node_modules', '.env'];

export async function runRepositoryChecks(
  discovery: DiscoveryResult,
  _config: LaunchProofConfig,
): Promise<CheckResult[]> {
  const started = Date.now();
  const findings: Finding[] = [];
  const paths = new Set(discovery.files.map((file) => file.path));

  if (!paths.has('.gitignore')) {
    findings.push(
      createFinding({
        checkId: 'configuration.repository',
        title: 'No .gitignore file',
        description:
          'The project does not define a .gitignore, so build output, dependencies, and environment files can be committed accidentally.',
        severity: 'medium',
        confidence: 'high',
        verification: 'observed',
        category: 'configuration',
        impact: 'Secrets and large generated directories can enter version control.',
        remediation: 'Add a .gitignore covering node_modules, build output, and .env files.',
        key: 'repo:gitignore-missing',
      }),
    );
  } else {
    const gitignore = discovery.files.find((file) => file.path === '.gitignore');
    const text = gitignore ? await discovery.cache.text(gitignore) : null;
    for (const required of GITIGNORE_REQUIRED) {
      if (
        text &&
        !new RegExp(`(?:^|/)\\s*${required.replace('.', '\\.')}(?:\\s|$|/|\\*)`, 'm').test(text)
      ) {
        findings.push(
          createFinding({
            checkId: 'configuration.repository',
            title: `.gitignore does not cover ${required}`,
            description: `The .gitignore file does not appear to ignore ${required}.`,
            severity: required === '.env' ? 'high' : 'medium',
            confidence: 'medium',
            verification: 'pattern',
            category: 'configuration',
            impact:
              required === '.env'
                ? 'Credentials can be committed and pushed by an ordinary broad git add.'
                : 'Dependencies can be committed, inflating the repository and obscuring review.',
            remediation: `Add ${required} to .gitignore.`,
            location: { file: '.gitignore' },
            key: `repo:gitignore:${required}`,
          }),
        );
      }
    }
  }
  const lockfileNames = ['package-lock.json', 'pnpm-lock.yaml', 'yarn.lock', 'bun.lockb'];
  const lockfileChecks = await Promise.all(
    lockfileNames.map(async (name) =>
      (await pathExists(path.join(discovery.rootDir, name))) ? name : null,
    ),
  );
  const lockfiles = lockfileChecks.filter((name): name is string => name !== null);
  if (discovery.packageJson && lockfiles.length === 0) {
    findings.push(
      createFinding({
        checkId: 'configuration.repository',
        title: 'No dependency lockfile',
        description: 'A package.json exists without a committed npm, pnpm, yarn, or bun lockfile.',
        severity: 'medium',
        confidence: 'high',
        verification: 'observed',
        category: 'configuration',
        impact:
          'Builds are not reproducible and can silently pick up compromised dependency versions.',
        remediation:
          'Commit the lockfile generated by your package manager and use frozen installs in CI.',
        key: 'repo:lockfile-missing',
      }),
    );
  }

  for (const [file, label, severity] of [
    ['README.md', 'README', 'low'],
    ['LICENSE', 'license', 'low'],
  ] as const) {
    if (!paths.has(file)) {
      findings.push(
        createFinding({
          checkId: 'configuration.repository',
          title: `Missing ${label} file`,
          description: `The repository has no ${file}.`,
          severity,
          confidence: 'high',
          verification: 'observed',
          category: 'configuration',
          impact:
            file === 'LICENSE'
              ? 'Without a license, others have no clear legal right to use the project.'
              : 'New contributors and users lack orientation.',
          remediation: `Add a ${file} file.`,
          key: `repo:${file}-missing`,
        }),
      );
    }
  }

  const hasCi = discovery.files.some(
    (file) => /^\.github\/workflows\/.+\.ya?ml$/.test(file.path) || file.path === '.gitlab-ci.yml',
  );
  if (!hasCi) {
    findings.push(
      createFinding({
        checkId: 'configuration.repository',
        title: 'No continuous integration workflow',
        description: 'No GitHub Actions or GitLab CI configuration was found.',
        severity: 'low',
        confidence: 'high',
        verification: 'observed',
        category: 'configuration',
        impact: 'Checks depend on local discipline and regressions can reach the default branch.',
        remediation:
          'Add a CI workflow that installs from the lockfile and runs lint, typecheck, tests, and build.',
        key: 'repo:ci-missing',
      }),
    );
  }

  const highSeverity = findings.filter(
    (finding) => finding.severity === 'high' || finding.severity === 'critical',
  );
  return [
    createCheck({
      id: 'configuration.repository',
      title: 'Repository hygiene',
      category: 'configuration',
      status: highSeverity.length > 0 ? 'fail' : findings.length > 0 ? 'warn' : 'pass',
      summary:
        findings.length === 0
          ? 'Repository hygiene basics are present.'
          : `${findings.length} repository hygiene item(s) need attention.`,
      findings,
      evidence: [
        { kind: 'metric', label: 'Lockfiles', value: lockfiles.join(', ') || 'none' },
        { kind: 'metric', label: 'CI workflow', value: hasCi ? 'present' : 'absent' },
      ],
      durationMs: Date.now() - started,
    }),
  ];
}

export function repositoryHygieneEnabled(config: LaunchProofConfig): boolean {
  return config.scan.include.length === 0;
}
